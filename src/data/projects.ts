/** Aggregates derived from the case studies above — never hardcoded, so the
 *  headline figures stay true if a project is added, edited or removed. */
const sum = (pick: (p: Project) => number | undefined) =>
  projects.reduce((total, p) => total + (pick(p) ?? 0), 0);

export const stats = {
  projectCount: projects.length,
  monthlyUsd: sum((p) => p.monthlyUsd),
  monthlyHours: sum((p) => p.monthlyHours),
  toolCount: new Set(projects.flatMap((p) => p.techStack)).size,
};

export const countFor = (cat: Category) =>
  cat === "All" ? projects.length : projects.filter((p) => p.category === cat).length;
